import plistlib, sys
# Read the extracted SystemPowerProfileDefaults.plist and emit a kernel
# header with a compact XML literal for OSUnserializeXML() embedding in
# IOPMrootDomain.cpp.  Usage:
#   7z e -o/tmp/pwb ROOTFS.HFS 'BrightonMaps10B329.N90OS/System/Library/
#     CoreServices/powerd.bundle/com.apple.SystemPowerProfileDefaults.plist'
#   python3 tools/dbg/gen_profiles.py > neighbor/xnu/iokit/Kernel/
#     I9100SystemPowerProfiles.h
src = "/tmp/pwb/com.apple.SystemPowerProfileDefaults.plist"
d = plistlib.load(open(src, "rb"))
arr = d["SystemProfileDefaults"]
out = ["<array>"]
for prof in arr:
    out.append("<dict>")
    for src_key, sub in prof.items():
        out.append("<key>%s</key>" % src_key)
        out.append("<dict>")
        for k, v in sub.items():
            out.append("<key>%s</key>" % k)
            if isinstance(v, bool):
                out.append("<true/>" if v else "<false/>")
            elif isinstance(v, int):
                out.append("<integer>%d</integer>" % v)
            else:
                out.append("<string>%s</string>" % str(v))
        out.append("</dict>")
    out.append("</dict>")
out.append("</array>")
xml = "".join(out)
print("/*")
print(" * iPhone3,1 iOS 6.1.3 (10B329) SystemProfileDefaults, verbatim from")
print(" * powerd.bundle/com.apple.SystemPowerProfileDefaults.plist.")
print(" * Generated by tools/dbg/gen_profiles.py - do not hand edit.")
print(" * len=%d" % len(xml))
print(" */")
print('static const char i9100SystemPowerProfilesXML[] =')
for i in range(0, len(xml), 100):
    print('    "%s"' % xml[i:i+100].replace('\\', '\\\\').replace('"', '\\"'))
print('    ;')
