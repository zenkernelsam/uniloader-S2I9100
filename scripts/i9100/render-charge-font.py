#!/usr/bin/env python3
"""Rasterize only local iOS6 percentage glyphs; the loader uses a small A8 table."""
import os,sys
if os.environ.get('I9100_CPU_CAPPED')!='1':
    os.execvpe('taskset',['taskset','-c','0-13','nice','-n10','ionice','-c2','-n7',sys.executable,'-B',__file__,*sys.argv[1:]],dict(os.environ,I9100_CPU_CAPPED='1'))
import argparse,ctypes as C,ctypes.util,hashlib,json
from pathlib import Path

class Generic(C.Structure):_fields_=[('data',C.c_void_p),('finalizer',C.c_void_p)]
class BBox(C.Structure):_fields_=[(x,C.c_long) for x in ('xmin','ymin','xmax','ymax')]
class Vector(C.Structure):_fields_=[('x',C.c_long),('y',C.c_long)]
class Metrics(C.Structure):_fields_=[(x,C.c_long) for x in ('width','height','horiBearingX','horiBearingY','horiAdvance','vertBearingX','vertBearingY','vertAdvance')]
class Bitmap(C.Structure):
    _fields_=[('rows',C.c_uint),('width',C.c_uint),('pitch',C.c_int),('buffer',C.POINTER(C.c_ubyte)),('num_grays',C.c_ushort),('pixel_mode',C.c_ubyte),('palette_mode',C.c_ubyte),('palette',C.c_void_p)]
class Slot(C.Structure):
    _fields_=[('library',C.c_void_p),('face',C.c_void_p),('next',C.c_void_p),('glyph_index',C.c_uint),('generic',Generic),('metrics',Metrics),('linearHoriAdvance',C.c_long),('linearVertAdvance',C.c_long),('advance',Vector),('format',C.c_uint),('bitmap',Bitmap),('left',C.c_int),('top',C.c_int)]
class Face(C.Structure):
    _fields_=[('num_faces',C.c_long),('face_index',C.c_long),('face_flags',C.c_long),('style_flags',C.c_long),('num_glyphs',C.c_long),('family_name',C.c_char_p),('style_name',C.c_char_p),('num_fixed_sizes',C.c_int),('available_sizes',C.c_void_p),('num_charmaps',C.c_int),('charmaps',C.c_void_p),('generic',Generic),('bbox',BBox),('units_per_EM',C.c_ushort),('ascender',C.c_short),('descender',C.c_short),('height',C.c_short),('max_advance_width',C.c_short),('max_advance_height',C.c_short),('underline_position',C.c_short),('underline_thickness',C.c_short),('glyph',C.POINTER(Slot)),('size',C.c_void_p),('charmap',C.c_void_p)]
def main():
    repo=Path(__file__).resolve().parents[2];p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--font',type=Path,required=True);p.add_argument('--output',type=Path,required=True)
    a=p.parse_args();font=a.font.resolve();out=a.output.resolve()
    assert font.is_relative_to(repo.parent/'assets') and font.is_file()
    assert out.is_relative_to(repo/'out') and not out.exists();out.mkdir(parents=True)
    assert hashlib.sha256(font.read_bytes()).hexdigest()=='8d8f75918ed6be55c395f761456918d307d7833f59d7cbaf37fb3089573ea4a5'
    ft=C.CDLL(ctypes.util.find_library('freetype'));lib=C.c_void_p();face=C.POINTER(Face)()
    ft.FT_Init_FreeType.argtypes=[C.POINTER(C.c_void_p)];ft.FT_New_Face.argtypes=[C.c_void_p,C.c_char_p,C.c_long,C.POINTER(C.POINTER(Face))]
    ft.FT_Set_Pixel_Sizes.argtypes=[C.POINTER(Face),C.c_uint,C.c_uint];ft.FT_Load_Char.argtypes=[C.POINTER(Face),C.c_ulong,C.c_int]
    assert ft.FT_Init_FreeType(C.byref(lib))==0 and ft.FT_New_Face(lib,str(font).encode(),0,C.byref(face))==0
    assert face.contents.family_name==b'Helvetica Neue' and face.contents.style_name==b'Regular'
    assert ft.FT_Set_Pixel_Sizes(face,0,28)==0
    rows=[];metrics=[]
    for char in '0123456789%-':
        assert ft.FT_Load_Char(face,ord(char),4)==0
        slot=face.contents.glyph.contents;bm=slot.bitmap
        assert bm.pixel_mode==2 and bm.pitch>0 and bm.width<=28 and bm.rows<=34
        alpha=bytearray(28*34)
        for y in range(bm.rows):
            for x in range(bm.width):alpha[y*28+x]=bm.buffer[y*bm.pitch+x]
        rows.append(alpha);metrics.append((bm.width,bm.rows,slot.left,slot.top,(slot.advance.x+32)//64))
    header=['/* Local iOS6 Helvetica Neue Regular, 28px A8 glyph subset.',' * Generated by scripts/i9100/render-charge-font.py; no runtime font library.',' * Font source SHA256: '+hashlib.sha256(font.read_bytes()).hexdigest()+' */','#ifndef I9100_CHARGE_FONT_H','#define I9100_CHARGE_FONT_H','#include <stdint.h>','struct i9100_charge_glyph {uint8_t width,height;int8_t left,top;uint8_t advance;};','static const struct i9100_charge_glyph i9100_charge_font_metrics[12]={']
    header += [' {'+','.join(map(str,v))+'},' for v in metrics];header+=['};','static const uint8_t i9100_charge_font_alpha[12][28*34]={']
    for alpha in rows:
        header.append(' {');header.extend('  '+','.join(map(str,alpha[i:i+28]))+',' for i in range(0,len(alpha),28));header.append(' },')
    header+=['};','#endif']
    (out/'i9100-charge-font.h').write_text('\n'.join(header)+'\n')
    (out/'glyphs.a8').write_bytes(b''.join(rows));(out/'result.json').write_text(json.dumps(dict(result='PASS',font_sha256=hashlib.sha256(font.read_bytes()).hexdigest(),face='Helvetica Neue Regular',pixels=28,glyphs='0123456789%-',metrics=metrics,header_sha256=hashlib.sha256((out/'i9100-charge-font.h').read_bytes()).hexdigest()),indent=2)+'\n')
    print('PASS local original Helvetica Neue Regular A8 subset',out)
if __name__=='__main__':main()

