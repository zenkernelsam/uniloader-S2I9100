#ifndef EXYNOS4210_H_	/* Include guard */
#define EXYNOS4210_H_

/* Debug UART: ttySAC2 (S5P/Exynos UART, same family as EXYNOS3475) */
#define EXYNOS4210_UART0_BASE		0x13800000
#define EXYNOS4210_UART1_BASE		0x13810000
#define EXYNOS4210_UART2_BASE		0x13820000
#define EXYNOS4210_UART3_BASE		0x13830000
#define EXYNOS4210_UART_BASE		EXYNOS4210_UART2_BASE
#define EXYNOS4210_ULCON		0x00
#define EXYNOS4210_UCON			0x04
#define EXYNOS4210_UFCON		0x08
#define EXYNOS4210_UMCON		0x0C
#define EXYNOS4210_UTRSTAT		0x10
#define EXYNOS4210_UERSTAT		0x14
#define EXYNOS4210_UFSTAT		0x18
#define EXYNOS4210_UTXH			0x20
#define EXYNOS4210_URXH			0x24
#define EXYNOS4210_UBRDIV		0x28
#define EXYNOS4210_UFRACVAL		0x2C

#define EXYNOS4210_UTRSTAT_TX_EMPTY	(1 << 1)
#define EXYNOS4210_UTRSTAT_RX_READY	(1 << 0)

/* GIC (PL390): distributor + cpu interface */
#define EXYNOS4210_GICC_BASE		0x10480000
#define EXYNOS4210_GICD_BASE		0x10490000

/* Interrupt combiner */
#define EXYNOS4210_COMBINER_BASE	0x10440000

/* Multi-Core Timer (MCT) */
#define EXYNOS4210_MCT_BASE		0x10050000

/* SDHCI hosts (standard SDHCI 2.0 + Samsung quirks)
 *  slot 0 = internal eMMC, slot 2 = external microSD, slot 3 = WiFi SDIO */
#define EXYNOS4210_SDHCI_BASE(n)	(0x12510000 + ((n) * 0x10000))
#define EXYNOS4210_SDHCI_EMMC_BASE	EXYNOS4210_SDHCI_BASE(0)
#define EXYNOS4210_SDHCI_SD_BASE	EXYNOS4210_SDHCI_BASE(2)
#define EXYNOS4210_SDHCI_WIFI_BASE	EXYNOS4210_SDHCI_BASE(3)

/* FIMD display controller (feeds LD9040 panel via parallel RGB) */
#define EXYNOS4210_FIMD0_BASE		0x11C00000
#define EXYNOS4210_FIMD_VIDCON0		0x0000
#define EXYNOS4210_FIMD_VIDCON1		0x0004
#define EXYNOS4210_FIMD_VIDTCON0	0x0010
#define EXYNOS4210_FIMD_VIDTCON1	0x0014
#define EXYNOS4210_FIMD_VIDTCON2	0x0018
#define EXYNOS4210_FIMD_WINCON0		0x0020
#define EXYNOS4210_FIMD_VIDOSD0A	0x0040
#define EXYNOS4210_FIMD_VIDOSD0B	0x0044
#define EXYNOS4210_FIMD_VIDOSD0C	0x0048
#define EXYNOS4210_FIMD_VIDW00ADD0B0	0x00A0
#define EXYNOS4210_FIMD_VIDW00ADD0B1	0x00D0
#define EXYNOS4210_FIMD_VIDW00ADD2	0x0100
#define EXYNOS4210_FIMD_VIDCON0_ENVID_F	(1 << 0)
#define EXYNOS4210_FIMD_VIDCON0_ENVID	(1 << 1)
#define EXYNOS4210_FIMD_WINCON_ENWIN	(1 << 0)
#define EXYNOS4210_FIMD_WINCON_BUFMODE	(1 << 14)
#define EXYNOS4210_FIMD_WINCON_BPPMODE_32BPP_A888	(0xd << 2)

/* System blocks */
#define EXYNOS4210_CHIPID_BASE		0x10000000
#define EXYNOS4210_PMU_BASE		0x10020000
#define EXYNOS4210_CMU_BASE		0x10030000
#define EXYNOS4210_WDT_BASE		0x10060000

/* CMU clock gating for SDMMC hosts (CLK_GATE_IP_PERIL @0xC950,
 * CLK_SRC_PERIL0 @0xC250, CLK_DIV_PERIL0 @0xC550 — Exynos4210 CMU map) */
#define EXYNOS4210_CLK_SRC_PERIL0	0xC250
#define EXYNOS4210_CLK_DIV_PERIL0	0xC550
#define EXYNOS4210_CLK_GATE_IP_PERIL	0xC950

/* DRAM */
#define EXYNOS4210_DRAM_BASE		0x40000000
#define EXYNOS4210_DRAM_SIZE		0x40000000	/* 1 GiB */

#endif /* EXYNOS4210_H_ */
